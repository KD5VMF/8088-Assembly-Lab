InitBpsClock PROC
        call GetTickLow
        mov WORD PTR [lastTick], ax
        xor ax, ax
        mov WORD PTR [txSecBytes], ax
        mov WORD PTR [rxSecBytes], ax
        mov WORD PTR [txBps], ax
        mov WORD PTR [rxBps], ax
        ret
InitBpsClock ENDP

GetTickLow PROC
        push ds
        mov ax, 0040h
        mov ds, ax
        mov ax, WORD PTR ds:[006Ch]
        pop ds
        ret
GetTickLow ENDP

UpdateBpsMaybe PROC
        push ax
        push bx
        call GetTickLow
        mov bx, ax
        sub ax, WORD PTR [lastTick]
        cmp ax, 18
        jae UBDoUpdate
        pop bx
        pop ax
        ret
UBDoUpdate:
        mov WORD PTR [lastTick], bx
        mov ax, WORD PTR [txSecBytes]
        mov WORD PTR [txBps], ax
        mov ax, WORD PTR [rxSecBytes]
        mov WORD PTR [rxBps], ax
        xor ax, ax
        mov WORD PTR [txSecBytes], ax
        mov WORD PTR [rxSecBytes], ax
        pop bx
        pop ax
        ret
UpdateBpsMaybe ENDP

