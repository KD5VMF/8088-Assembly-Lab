DelayBySetting PROC
        cmp BYTE PTR [delayMode], 0
        je DelayDone
        cmp BYTE PTR [delayMode], 1
        je DelayFast
        cmp BYTE PTR [delayMode], 2
        je DelayNormal
        jmp DelaySlow

DelayFast:
        mov cx, 0001h
        call DelayCX
        ret
DelayNormal:
        mov cx, 0005h
        call DelayCX
        ret
DelaySlow:
        mov cx, 0012h
        call DelayCX
        ret
DelayDone:
        ret
DelayBySetting ENDP

