SerialWriteChar PROC
        push ax
        push cx
        push dx
        mov ah, al
        mov cx, 0FFFFh
SWCWait:
        mov dx, WORD PTR [comBase]
        add dx, 5
        in al, dx
        test al, 20h
        jnz SWCReady
        loop SWCWait
SWCReady:
        mov dx, WORD PTR [comBase]
        mov al, ah
        out dx, al
        inc WORD PTR [txSecBytes]
        pop dx
        pop cx
        pop ax
        ret
SerialWriteChar ENDP

SerialReadLine PROC
        push ax
        push bx
        push di

        mov di, OFFSET rspBuf
        xor bx, bx

SRLLoop:
        call SerialReadByteTimeout
        jc SRLGotByte
        jmp SRLTimeout

SRLGotByte:
        inc WORD PTR [rxSecBytes]
        cmp al, 13
        je SRLMaybeDone
        cmp al, 10
        je SRLMaybeDone
        cmp al, 0
        je SRLLoop

        cmp bx, 180
        jb SRLStore
        jmp SRLLoop

SRLStore:
        mov BYTE PTR [di], al
        inc di
        inc bx
        jmp SRLLoop

SRLMaybeDone:
        cmp bx, 0
        jne SRLDone
        jmp SRLLoop

SRLDone:
        mov al, 0
        mov BYTE PTR [di], al
        pop di
        pop bx
        pop ax
        stc
        ret

SRLTimeout:
        mov al, 0
        mov BYTE PTR [di], al
        pop di
        pop bx
        pop ax
        clc
        ret
SerialReadLine ENDP

SerialReadByteTimeout PROC
        push bx
        push cx
        push dx

        mov cx, WORD PTR [rxTimeoutOuter]
RBTOuter:
        mov bx, 0FFFFh
RBTInner:
        mov dx, WORD PTR [comBase]
        add dx, 5
        in al, dx
        test al, 01h
        jnz RBTGot
        dec bx
        jnz RBTInner
        loop RBTOuter

        pop dx
        pop cx
        pop bx
        clc
        ret

RBTGot:
        mov dx, WORD PTR [comBase]
        in al, dx
        pop dx
        pop cx
        pop bx
        stc
        ret
SerialReadByteTimeout ENDP

