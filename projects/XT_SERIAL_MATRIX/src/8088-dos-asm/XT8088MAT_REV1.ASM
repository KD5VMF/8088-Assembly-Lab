IsRspLine PROC
        push bx
        mov bx, OFFSET rspBuf
        cmp BYTE PTR [bx], 'R'
        jne IRBad
        cmp BYTE PTR [bx+1], 'S'
        jne IRBad
        cmp BYTE PTR [bx+2], 'P'
        jne IRBad
        pop bx
        stc
        ret
IRBad:
        pop bx
        clc
        ret
IsRspLine ENDP

