; -----------------------------------------------------------------------------
; Program entry
; -----------------------------------------------------------------------------
main PROC
        mov ax, @data
        mov ds, ax

        call SettingsMenu
        call SerialInit
        call InitBpsClock
        call DrawRunScreen

MainLoop:
        inc WORD PTR [seqNum]
        call BuildPrimeRequest

        call DrawWorkSent

        mov si, OFFSET reqBuf
        call SerialSendZString
        call SerialSendCRLF
        inc WORD PTR [statReq]

        call AdvanceWorkStart
        call UpdateBpsMaybe

        mov dh, 10
        call ClearLine
        mov dh, 10
        mov dl, 1
        mov bh, WARN_ATTR
        mov si, OFFSET txtWaiting
        call PrintAt

        call SerialReadLine
        jc GotResponseNear
        jmp NoResponse

GotResponseNear:
        inc WORD PTR [statRsp]
        call IsRspLine
        jc GoodMatrixResponse
        call DrawRawResponse
        jmp AfterResponse

GoodMatrixResponse:
        call DrawPrimeResult
        jmp AfterResponse

NoResponse:
        inc WORD PTR [statTimeout]
        mov dh, 10
        call ClearLine
        mov dh, 10
        mov dl, 1
        mov bh, WARN_ATTR
        mov si, OFFSET txtTimeout
        call PrintAt

AfterResponse:
        call UpdateBpsMaybe
        call DrawStats
        call DelayBySetting

        call CheckKey
        jnc MainLoopAgain
        jmp KeyWasPressed

MainLoopAgain:
        jmp MainLoop

KeyWasPressed:
        cmp al, 's'
        je KeySettingsLower
        cmp al, 'S'
        je KeySettingsUpper
        cmp al, 'r'
        je KeyRestartLower
        cmp al, 'R'
        je KeyRestartUpper
        cmp al, 'q'
        je KeyQuitLower
        cmp al, 'Q'
        je KeyQuitUpper
        cmp al, 27
        je KeyQuitEsc
        jmp MainLoop

KeySettingsLower:
        jmp ChangeSettings
KeySettingsUpper:
        jmp ChangeSettings
KeyRestartLower:
        jmp RestartRanges
KeyRestartUpper:
        jmp RestartRanges
KeyQuitLower:
        jmp ProgramQuit
KeyQuitUpper:
        jmp ProgramQuit
KeyQuitEsc:
        jmp ProgramQuit

ChangeSettings:
        call SettingsMenu
        call SerialInit
        call InitBpsClock
        call DrawRunScreen
        jmp MainLoop

RestartRanges:
        mov WORD PTR [workStart], 12345
        mov WORD PTR [seedB], 54321
        inc WORD PTR [statRestart]
        mov dh, 18
        call ClearLine
        mov dh, 18
        mov dl, 0
        mov bh, WARN_ATTR
        mov si, OFFSET txtRestarted
        call PrintAt
        jmp MainLoop

ProgramQuit:
        mov dh, 23
        call ClearLine
        mov dh, 23
        mov dl, 0
        mov bh, WARN_ATTR
        mov si, OFFSET txtQuitMsg
        call PrintAt

        mov ah, 00h
        int 16h

        mov ax, 4C00h
        int 21h
main ENDP

