        push ax
        push bx
        push cx
DCXOuter:
        mov bx, 0FFFFh
DCXInner:
        dec bx
        jnz DCXInner
        loop DCXOuter
        pop cx
        pop bx
        pop ax
        ret
DelayCX ENDP

