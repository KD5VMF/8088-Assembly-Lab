BuildPrimeRequest PROC
        mov di, OFFSET reqBuf

        mov si, OFFSET strPRM
        call AppendZString

        mov ax, WORD PTR [seqNum]
        call AppendDec5
        call AppendComma

        ; Matrix size N, usually 04096.
        mov ax, WORD PTR [chunkSize]
        call AppendDec5
        call AppendComma

        ; Seed A generated by the 8088.
        mov ax, WORD PTR [workStart]
        call AppendDec5
        call AppendComma

        ; Seed B generated by the 8088.
        mov ax, WORD PTR [seedB]
        call AppendDec5

        ; Calculate XOR checksum over body.
        push di
        mov si, OFFSET reqBuf
        mov bx, di
        sub bx, OFFSET reqBuf
        xor dl, dl
ChkLoop:
        cmp bx, 0
        jne ChkDoChar
        jmp ChkDone
ChkDoChar:
        lodsb
        xor dl, al
        dec bx
        jmp ChkLoop
ChkDone:
        pop di

        mov al, '*'
        call AppendChar
        mov al, dl
        call AppendHexByte

        mov al, 0
        call AppendChar
        ret
BuildPrimeRequest ENDP

AdvanceWorkStart PROC
        ; Generate the next two 16-bit matrix seeds on the 8088.
        ; seed = seed * 25173 + 13849, modulo 65536
        mov ax, WORD PTR [workStart]
        mov bx, 25173
        mul bx
        add ax, 13849
        cmp ax, 0
        jne AWSStoreA
        mov ax, 1
AWSStoreA:
        mov WORD PTR [workStart], ax

        ; second independent sequence for B
        mov ax, WORD PTR [seedB]
        mov bx, 17405
        mul bx
        add ax, 40709
        cmp ax, 0
        jne AWSStoreB
        mov ax, 7
AWSStoreB:
        mov WORD PTR [seedB], ax
        ret
AdvanceWorkStart ENDP

