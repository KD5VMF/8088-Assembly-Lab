AppendDec5 PROC
        push ax
        push bx
        push dx

        mov bx, 10000
        xor dx, dx
        div bx
        add al, '0'
        call AppendChar
        mov ax, dx

        mov bx, 1000
        xor dx, dx
        div bx
        add al, '0'
        call AppendChar
        mov ax, dx

        mov bx, 100
        xor dx, dx
        div bx
        add al, '0'
        call AppendChar
        mov ax, dx

        mov bx, 10
        xor dx, dx
        div bx
        add al, '0'
        call AppendChar
        mov ax, dx

        add al, '0'
        call AppendChar

        pop dx
        pop bx
        pop ax
        ret
AppendDec5 ENDP

AppendHexByte PROC
        push ax
        push bx
        mov bl, al
        mov al, bl
        shr al, 1
        shr al, 1
        shr al, 1
        shr al, 1
        call AppendHexNibble
        mov al, bl
        and al, 0Fh
        call AppendHexNibble
        pop bx
        pop ax
        ret
AppendHexByte ENDP

