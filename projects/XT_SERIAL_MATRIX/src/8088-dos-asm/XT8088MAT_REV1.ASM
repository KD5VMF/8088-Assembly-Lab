; -----------------------------------------------------------------------------
; XT8088MAT_REV1.ASM
;
; 8088 / 8086 DOS EXE - Serial Matrix Co-Processor Client
;
; Build with old Borland tools:
;     TASM XT8088MAT_REV1
;     TLINK XT8088MAT_REV1
;     XT8088MAT_REV1
;
; What this does:
;   - The 8088 asks for COM port, baud rate, delay, and matrix size.
;   - It initializes a real 8250/16450/16550-compatible serial port.
;   - It sends matrix multiplication data-set requests to a C# program over RS-232.
;   - The PC performs the matrix math and sends a display-ready result line back.
;   - The 8088 prints everything to VGA text RAM.
;   - The 8088 shows current TX and RX bytes per second.
;
; Serial request sent by the 8088:
;     MAT,00001,04096,12345,54321*XX<CR><LF>
;
; Fields:
;     MAT      = matrix multiply request
;     00001    = sequence number
;     04096    = matrix size N
;     12345    = seed A, 54321 = seed B
;     XX       = XOR checksum of every character before '*'
;
; Example C# response:
;     RSP,00001,04096,12345,54321,1234567890,1234567890,1234567890,1234567890,1234567890,12345*XX
;
; Runtime keys:
;     S   Change settings / reinitialize serial
;     R   Generate/reset matrix seeds
;     Q   Quit
;     ESC Quit
;
; Notes:
;   - Uses polling, not IRQs.
;   - Uses direct B800h text video, green-on-black style.
;   - No disk writes while running.
;   - Designed for TASM/TLINK as a DOS .EXE.
;   - REV8 uses explicit BYTE PTR / WORD PTR memory operands to avoid
;     TASM constant/immediate ambiguity warnings.
; -----------------------------------------------------------------------------

