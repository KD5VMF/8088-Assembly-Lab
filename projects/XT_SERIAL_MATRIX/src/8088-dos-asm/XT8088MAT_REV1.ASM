SerialInit PROC
        ; Disable UART interrupts.
        mov dx, WORD PTR [comBase]
        inc dx
        mov al, 00h
        out dx, al

        ; Enable DLAB.
        mov dx, WORD PTR [comBase]
        add dx, 3
        mov al, 80h
        out dx, al

        ; Divisor latch low/high.
        mov ax, WORD PTR [baudDivisor]
        mov dx, WORD PTR [comBase]
        out dx, al
        inc dx
        mov al, ah
        out dx, al

        ; 8 data bits, no parity, 1 stop bit. DLAB off.
        mov dx, WORD PTR [comBase]
        add dx, 3
        mov al, 03h
        out dx, al

        ; FIFO control. 00h is safe for 8250. 16550 ignores or disables FIFO.
        mov dx, WORD PTR [comBase]
        add dx, 2
        mov al, 00h
        out dx, al

        ; Modem control: DTR + RTS + OUT2.
        mov dx, WORD PTR [comBase]
        add dx, 4
        mov al, 0Bh
        out dx, al
        ret
SerialInit ENDP

SerialSendZString PROC
SSZLoop:
